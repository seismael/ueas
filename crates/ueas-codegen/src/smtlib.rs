//! Universal Formal Prover IR: `SMT-LIB2` Verification Condition Generator (Z3 / CVC5 / Alt-Ergo).

use crate::common::{CodeGenerator, GeneratedArtifact};
use ueas_hir::hir::{BinaryOp, Expr, Program, UnaryOp};
use ueas_hir::types::{PrimitiveType, Type};

pub struct SmtLib2Target;

impl CodeGenerator for SmtLib2Target {
    fn target_id(&self) -> &'static str {
        "smt2"
    }
    fn file_extension(&self) -> &'static str {
        "smt2"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from("; Generated by UEAS v2.0 SmtLib2Target\n(set-logic ALL)\n\n");
        for algo in &program.algorithms {
            out.push_str(&format!("; === Algorithm {} ===\n(push)\n", algo.name));
            for p in &algo.parameters {
                out.push_str(&format!("(declare-const {} {})\n", p.name, smt_sort(&p.ty)));
            }
            let res_name = algo.postcondition_binding.as_deref().unwrap_or("result");
            if !matches!(
                algo.return_type,
                Type::Primitive {
                    prim: PrimitiveType::Void
                }
            ) {
                out.push_str(&format!(
                    "(declare-const {res_name} {})\n",
                    smt_sort(&algo.return_type)
                ));
            }
            for req in &algo.preconditions {
                out.push_str(&format!("(assert {})\n", fmt_smt_expr(req)));
            }
            for post in &algo.postconditions {
                out.push_str(&format!(
                    "; Verify negation of postcondition is unsat\n(assert (not {}))\n",
                    fmt_smt_expr(post)
                ));
            }
            out.push_str("(check-sat)\n(pop)\n\n");
        }
        Ok(GeneratedArtifact {
            target: "smt2".to_string(),
            extension: "smt2".to_string(),
            code: out,
            test_code: None,
        })
    }
}

fn smt_sort(ty: &Type) -> String {
    match ty {
        Type::Primitive {
            prim: PrimitiveType::Int | PrimitiveType::Int64 | PrimitiveType::UInt64,
        } => "Int".to_string(),
        Type::Primitive {
            prim: PrimitiveType::Bool,
        } => "Bool".to_string(),
        Type::Primitive {
            prim: PrimitiveType::Real,
        } => "Real".to_string(),
        Type::Primitive {
            prim: PrimitiveType::String,
        } => "String".to_string(),
        Type::List { elem } => format!("(Seq {})", smt_sort(elem)),
        _ => "Int".to_string(),
    }
}

fn fmt_smt_expr(expr: &Expr) -> String {
    match expr {
        Expr::IntLit { value, .. } => value.clone(),
        Expr::RealLit { value, .. } => format!("{value}"),
        Expr::BoolLit { value, .. } => format!("{value}"),
        Expr::StringLit { value, .. } => format!("\"{value}\""),
        Expr::Ident { name, .. } => name.clone(),
        Expr::Unary { op, operand, .. } => match op {
            UnaryOp::Neg => format!("(- {})", fmt_smt_expr(operand)),
            UnaryOp::Not => format!("(not {})", fmt_smt_expr(operand)),
            UnaryOp::BitNot => format!("(bvnot {})", fmt_smt_expr(operand)),
        },
        Expr::Binary {
            op, left, right, ..
        } => {
            let sym = match op {
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "div",
                BinaryOp::Mod => "mod",
                BinaryOp::Eq => "=",
                BinaryOp::Neq => "distinct",
                BinaryOp::Lt => "<",
                BinaryOp::Le => "<=",
                BinaryOp::Gt => ">",
                BinaryOp::Ge => ">=",
                BinaryOp::And => "and",
                BinaryOp::Or => "or",
                BinaryOp::Implies => "=>",
                _ => "=",
            };
            format!("({sym} {} {})", fmt_smt_expr(left), fmt_smt_expr(right))
        }
        Expr::Quantifier {
            is_forall,
            var,
            iterable,
            body,
            ..
        } => {
            let q = if *is_forall { "forall" } else { "exists" };
            if let Expr::Range { start, end, .. } = iterable.as_ref() {
                format!(
                    "({q} (({var} Int)) (=> (and (<= {} {var}) (< {var} {})) {}))",
                    fmt_smt_expr(start),
                    fmt_smt_expr(end),
                    fmt_smt_expr(body)
                )
            } else {
                format!("({q} (({var} Int)) {})", fmt_smt_expr(body))
            }
        }
        _ => "true".to_string(),
    }
}
