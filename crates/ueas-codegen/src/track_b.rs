fn emit_dafny_stmts(stmts: &[Stmt], ret_name: &str, depth: usize, out: &mut String) {
    let pad = indent(depth);
    for s in stmts {
        match s {
            Stmt::Let { name, init, .. } | Stmt::Const { name, init, .. } => {
                out.push_str(&format!("{pad}var {name} := {};\n", fmt_logic(init)));
            }
            Stmt::Assign { target, value, .. } => {
                out.push_str(&format!(
                    "{pad}{} := {};\n",
                    fmt_lvalue(target),
                    fmt_logic(value)
                ));
            }
            Stmt::If {
                condition,
                then_body,
                else_if_branches,
                else_body,
                ..
            } => {
                out.push_str(&format!("{pad}if ({}) {{\n", fmt_logic(condition)));
                emit_dafny_stmts(then_body, ret_name, depth + 1, out);
                for (ec, eb) in else_if_branches {
                    out.push_str(&format!("{pad}}} else if ({}) {{\n", fmt_logic(ec)));
                    emit_dafny_stmts(eb, ret_name, depth + 1, out);
                }
                if let Some(eb) = else_body {
                    out.push_str(&format!("{pad}}} else {{\n"));
                    emit_dafny_stmts(eb, ret_name, depth + 1, out);
                }
                out.push_str(&format!("{pad}}}\n"));
            }
            Stmt::While {
                condition,
                invariants,
                decreases,
                body,
                ..
            } => {
                out.push_str(&format!("{pad}while ({})\n", fmt_logic(condition)));
                for inv in invariants {
                    out.push_str(&format!("{pad}    invariant {}\n", fmt_logic(inv)));
                }
                if let Some(d) = decreases {
                    out.push_str(&format!("{pad}    decreases {}\n", fmt_logic(d)));
                }
                out.push_str(&format!("{pad}{{\n"));
                emit_dafny_stmts(body, ret_name, depth + 1, out);
                out.push_str(&format!("{pad}}}\n"));
            }
            Stmt::Return { value, .. } => {
                if let Some(v) = value {
                    out.push_str(&format!("{pad}{ret_name} := {};\n", fmt_logic(v)));
                }
                out.push_str(&format!("{pad}return;\n"));
            }
            Stmt::Assert { condition, .. } => {
                out.push_str(&format!("{pad}assert {};\n", fmt_logic(condition)));
            }
            _ => {}
        }
    }
}

fn emit_lean_stmts(stmts: &[Stmt], depth: usize, out: &mut String) {
    let pad = indent(depth);
    for s in stmts {
        match s {
            Stmt::Let { name, init, .. } | Stmt::Const { name, init, .. } => {
                out.push_str(&format!("{pad}let mut {name} := {}\n", fmt_logic(init)));
            }
            Stmt::Assign { target, value, .. } => {
                out.push_str(&format!(
                    "{pad}{} := {}\n",
                    fmt_lvalue(target),
                    fmt_logic(value)
                ));
            }
            Stmt::If {
                condition,
                then_body,
                else_if_branches,
                else_body,
                ..
            } => {
                out.push_str(&format!("{pad}if {} then\n", fmt_logic(condition)));
                emit_lean_stmts(then_body, depth + 1, out);
                for (ec, eb) in else_if_branches {
                    out.push_str(&format!("{pad}else if {} then\n", fmt_logic(ec)));
                    emit_lean_stmts(eb, depth + 1, out);
                }
                if let Some(eb) = else_body {
                    out.push_str(&format!("{pad}else\n"));
                    emit_lean_stmts(eb, depth + 1, out);
                }
            }
            Stmt::While {
                condition, body, ..
            } => {
                out.push_str(&format!("{pad}while {} do\n", fmt_logic(condition)));
                emit_lean_stmts(body, depth + 1, out);
            }
            Stmt::Return { value, .. } => {
                let v = value
                    .as_ref()
                    .map(fmt_logic)
                    .unwrap_or_else(|| "()".to_string());
                out.push_str(&format!("{pad}return {v}\n"));
            }
            _ => {}
        }
    }
}

fn emit_verus_stmts(stmts: &[Stmt], depth: usize, out: &mut String) {
    let pad = indent(depth);
    for s in stmts {
        match s {
            Stmt::Let { name, init, .. } | Stmt::Const { name, init, .. } => {
                out.push_str(&format!("{pad}let mut {name} = {};\n", fmt_logic(init)));
            }
            Stmt::Assign { target, value, .. } => {
                out.push_str(&format!(
                    "{pad}{} = {};\n",
                    fmt_lvalue(target),
                    fmt_logic(value)
                ));
            }
            Stmt::If {
                condition,
                then_body,
                else_if_branches,
                else_body,
                ..
            } => {
                out.push_str(&format!("{pad}if {} {{\n", fmt_logic(condition)));
                emit_verus_stmts(then_body, depth + 1, out);
                for (ec, eb) in else_if_branches {
                    out.push_str(&format!("{pad}}} else if {} {{\n", fmt_logic(ec)));
                    emit_verus_stmts(eb, depth + 1, out);
                }
                if let Some(eb) = else_body {
                    out.push_str(&format!("{pad}}} else {{\n"));
                    emit_verus_stmts(eb, depth + 1, out);
                }
                out.push_str(&format!("{pad}}}\n"));
            }
            Stmt::While {
                condition,
                invariants,
                decreases,
                body,
                ..
            } => {
                out.push_str(&format!("{pad}while {}\n", fmt_logic(condition)));
                if !invariants.is_empty() {
                    out.push_str(&format!("{pad}    invariant\n"));
                    for inv in invariants {
                        out.push_str(&format!("{pad}        {},\n", fmt_logic(inv)));
                    }
                }
                if let Some(d) = decreases {
                    out.push_str(&format!("{pad}    decreases {},\n", fmt_logic(d)));
                }
                out.push_str(&format!("{pad}{{\n"));
                emit_verus_stmts(body, depth + 1, out);
                out.push_str(&format!("{pad}}}\n"));
            }
            Stmt::Return { value, .. } => {
                let v = value.as_ref().map(fmt_logic).unwrap_or_default();
                out.push_str(&format!("{pad}return {v};\n"));
            }
            _ => {}
        }
    }
}

fn fmt_lvalue(lv: &LValue) -> String {
    match lv {
        LValue::Var { name, .. } => name.clone(),
        LValue::Index { target, index, .. } => {
            format!("{}[{}]", fmt_lvalue(target), fmt_logic(index))
        }
        LValue::Field { target, field, .. } => format!("{}.{field}", fmt_lvalue(target)),
    }
}

fn fmt_logic(expr: &Expr) -> String {
    match expr {
        Expr::IntLit { value, .. } => value.clone(),
        Expr::RealLit { value, .. } => format!("{value}"),
        Expr::BoolLit { value, .. } => format!("{value}"),
        Expr::StringLit { value, .. } => format!("\"{value}\""),
        Expr::NoneLit { .. } => "None".to_string(),
        Expr::Ident { name, .. } => name.clone(),
        Expr::Unary { op, operand, .. } => match op {
            UnaryOp::Neg => format!("(-{})", fmt_logic(operand)),
            UnaryOp::Not => format!("(!{})", fmt_logic(operand)),
            UnaryOp::BitNot => format!("(~{})", fmt_logic(operand)),
        },
        Expr::Binary {
            op, left, right, ..
        } => {
            let sym = match op {
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "/",
                BinaryOp::Mod => "%",
                BinaryOp::Eq => "==",
                BinaryOp::Neq => "!=",
                BinaryOp::Lt => "<",
                BinaryOp::Le => "<=",
                BinaryOp::Gt => ">",
                BinaryOp::Ge => ">=",
                BinaryOp::And => "&&",
                BinaryOp::Or => "||",
                BinaryOp::Implies => "==>",
                _ => "==",
            };
            format!("({} {sym} {})", fmt_logic(left), fmt_logic(right))
        }
        Expr::Call { callee, args, .. } => {
            let a: Vec<String> = args.iter().map(|x| fmt_logic(&x.value)).collect();
            format!("{callee}({})", a.join(", "))
        }
        Expr::Field { target, field, .. } => {
            if field == "length" || field == "len" {
                format!("|{}|", fmt_logic(target))
            } else {
                format!("{}.{field}", fmt_logic(target))
            }
        }
        Expr::Index { target, index, .. } => format!("{}[{}]", fmt_logic(target), fmt_logic(index)),
        Expr::Quantifier {
            is_forall,
            var,
            iterable,
            body,
            ..
        } => {
            let q = if *is_forall { "forall" } else { "exists" };
            if let Expr::Range { start, end, .. } = iterable.as_ref() {
                format!(
                    "({q} {var} :: {} <= {var} < {} ==> {})",
                    fmt_logic(start),
                    fmt_logic(end),
                    fmt_logic(body)
                )
            } else {
                format!("({q} {var} :: {})", fmt_logic(body))
            }
        }
        _ => "true".to_string(),
    }
}

fn fmt_tla_expr(expr: &Expr) -> String {
    match expr {
        Expr::Binary {
            op, left, right, ..
        } => {
            let sym = match op {
                BinaryOp::And => "/\\",
                BinaryOp::Or => "\\/",
                BinaryOp::Implies => "=>",
                BinaryOp::Eq => "=",
                BinaryOp::Neq => "#",
                BinaryOp::Le => "<=",
                BinaryOp::Ge => ">=",
                BinaryOp::Lt => "<",
                BinaryOp::Gt => ">",
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "\\div",
                _ => "=",
            };
            format!("({} {sym} {})", fmt_tla_expr(left), fmt_tla_expr(right))
        }
        Expr::Quantifier {
            is_forall,
            var,
            iterable,
            body,
            ..
        } => {
            let q = if *is_forall { "\\A" } else { "\\E" };
            if let Expr::Range { start, end, .. } = iterable.as_ref() {
                format!(
                    "({q} {var} \\in ({}..({} - 1)) : {})",
                    fmt_tla_expr(start),
                    fmt_tla_expr(end),
                    fmt_tla_expr(body)
                )
            } else {
                format!("({q} {var} : {})", fmt_tla_expr(body))
            }
        }
        Expr::Field { target, field, .. } => {
            if field == "length" || field == "len" {
                format!("Len({})", fmt_tla_expr(target))
            } else {
                format!("{}.{field}", fmt_tla_expr(target))
            }
        }
        _ => fmt_logic(expr),
    }
}
