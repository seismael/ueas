//! Track B formal verification targets: Dafny 4, Lean 4, Verus, Quint, TLA+.

use crate::common::{indent, CodeGenerator, GeneratedArtifact};
use ueas_hir::hir::{BinaryOp, Expr, LValue, Program, Stmt, UnaryOp};
use ueas_hir::types::{PrimitiveType, Type};

pub struct DafnyTarget;
pub struct LeanTarget;
pub struct VerusTarget;
pub struct QuintTarget;
pub struct TlaTarget;

impl CodeGenerator for DafnyTarget {
    fn target_id(&self) -> &'static str {
        "dafny"
    }
    fn file_extension(&self) -> &'static str {
        "dfy"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from("// Generated by UEAS v2.0 DafnyTarget\n\n");
        for algo in &program.algorithms {
            let params: Vec<String> = algo
                .parameters
                .iter()
                .map(|p| format!("{}: {}", p.name, dafny_type(&p.ty)))
                .collect();
            let ret_name = algo.postcondition_binding.as_deref().unwrap_or("res");
            out.push_str(&format!(
                "method {}({}) returns ({ret_name}: {})\n",
                algo.name,
                params.join(", "),
                dafny_type(&algo.return_type)
            ));
            for req in &algo.preconditions {
                out.push_str(&format!("    requires {}\n", fmt_logic(req)));
            }
            for post in &algo.postconditions {
                out.push_str(&format!("    ensures {}\n", fmt_logic(post)));
            }
            out.push_str("{\n");
            emit_dafny_stmts(&algo.body, ret_name, 1, &mut out);
            out.push_str("}\n\n");
        }
        Ok(GeneratedArtifact {
            target: "dafny".to_string(),
            extension: "dfy".to_string(),
            code: out,
            test_code: None,
        })
    }
}

impl CodeGenerator for LeanTarget {
    fn target_id(&self) -> &'static str {
        "lean4"
    }
    fn file_extension(&self) -> &'static str {
        "lean"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from("-- Generated by UEAS v2.0 LeanTarget (Lean 4)\n\n");
        for algo in &program.algorithms {
            let params: Vec<String> = algo
                .parameters
                .iter()
                .map(|p| format!("({}: {})", p.name, lean_type(&p.ty)))
                .collect();
            out.push_str(&format!(
                "def {} {} : {} := Id.run do\n",
                algo.name,
                params.join(" "),
                lean_type(&algo.return_type)
            ));
            emit_lean_stmts(&algo.body, 1, &mut out);
            out.push('\n');
            for (i, post) in algo.postconditions.iter().enumerate() {
                out.push_str(&format!(
                    "-- Specification obligation {i}: {}\n",
                    fmt_logic(post)
                ));
            }
            out.push('\n');
        }
        Ok(GeneratedArtifact {
            target: "lean4".to_string(),
            extension: "lean".to_string(),
            code: out,
            test_code: None,
        })
    }
}

impl CodeGenerator for VerusTarget {
    fn target_id(&self) -> &'static str {
        "verus"
    }
    fn file_extension(&self) -> &'static str {
        "rs"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from(
            "// Generated by UEAS v2.0 VerusTarget\nuse vstd::prelude::*;\n\nverus! {\n\n",
        );
        for algo in &program.algorithms {
            let params: Vec<String> = algo
                .parameters
                .iter()
                .map(|p| format!("{}: {}", p.name, verus_type(&p.ty)))
                .collect();
            let ret_name = algo.postcondition_binding.as_deref().unwrap_or("res");
            out.push_str(&format!(
                "pub fn {}({}) -> ({ret_name}: {})\n",
                algo.name,
                params.join(", "),
                verus_type(&algo.return_type)
            ));
            if !algo.preconditions.is_empty() {
                out.push_str("    requires\n");
                for req in &algo.preconditions {
                    out.push_str(&format!("        {},\n", fmt_logic(req)));
                }
            }
            if !algo.postconditions.is_empty() {
                out.push_str("    ensures\n");
                for post in &algo.postconditions {
                    out.push_str(&format!("        {},\n", fmt_logic(post)));
                }
            }
            out.push_str("{\n");
            emit_verus_stmts(&algo.body, 1, &mut out);
            out.push_str("}\n\n");
        }
        out.push_str("} // verus!\n");
        Ok(GeneratedArtifact {
            target: "verus".to_string(),
            extension: "rs".to_string(),
            code: out,
            test_code: None,
        })
    }
}

impl CodeGenerator for QuintTarget {
    fn target_id(&self) -> &'static str {
        "quint"
    }
    fn file_extension(&self) -> &'static str {
        "qnt"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mod_name = program
            .module
            .as_deref()
            .unwrap_or("ueas_spec")
            .replace('.', "_");
        let mut out = format!("// Generated by UEAS v2.0 QuintTarget\nmodule {mod_name} {{\n");
        for algo in &program.algorithms {
            let params: Vec<String> = algo
                .parameters
                .iter()
                .map(|p| format!("{}: {}", p.name, quint_type(&p.ty)))
                .collect();
            let req_expr = if algo.preconditions.is_empty() {
                "true".to_string()
            } else {
                algo.preconditions
                    .iter()
                    .map(fmt_logic)
                    .collect::<Vec<_>>()
                    .join(" and ")
            };
            out.push_str(&format!(
                "    pure def {}_pre({}): bool = {req_expr}\n",
                algo.name,
                params.join(", ")
            ));
            let post_expr = if algo.postconditions.is_empty() {
                "true".to_string()
            } else {
                algo.postconditions
                    .iter()
                    .map(fmt_logic)
                    .collect::<Vec<_>>()
                    .join(" and ")
            };
            out.push_str(&format!(
                "    pure def {}_post({}): bool = {post_expr}\n",
                algo.name,
                params.join(", ")
            ));
        }
        out.push_str("}\n");
        Ok(GeneratedArtifact {
            target: "quint".to_string(),
            extension: "qnt".to_string(),
            code: out,
            test_code: None,
        })
    }
}

impl CodeGenerator for TlaTarget {
    fn target_id(&self) -> &'static str {
        "tla"
    }
    fn file_extension(&self) -> &'static str {
        "tla"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mod_name = program
            .module
            .as_deref()
            .unwrap_or("UEAS")
            .replace('.', "_");
        let mut out = format!("---- MODULE {mod_name} ----\nEXTENDS Integers, Sequences\n\n");
        for algo in &program.algorithms {
            let params: Vec<String> = algo.parameters.iter().map(|p| p.name.clone()).collect();
            let pre_body = if algo.preconditions.is_empty() {
                "TRUE".to_string()
            } else {
                algo.preconditions
                    .iter()
                    .map(fmt_tla_expr)
                    .collect::<Vec<_>>()
                    .join(" /\\ ")
            };
            out.push_str(&format!(
                "{}_Pre({}) == {pre_body}\n\n",
                algo.name,
                params.join(", ")
            ));
            let post_body = if algo.postconditions.is_empty() {
                "TRUE".to_string()
            } else {
                algo.postconditions
                    .iter()
                    .map(fmt_tla_expr)
                    .collect::<Vec<_>>()
                    .join(" /\\ ")
            };
            out.push_str(&format!(
                "{}_Post({}) == {post_body}\n\n",
                algo.name,
                params.join(", ")
            ));
        }
        out.push_str("====\n");
        Ok(GeneratedArtifact {
            target: "tla".to_string(),
            extension: "tla".to_string(),
            code: out,
            test_code: None,
        })
    }
}

fn dafny_type(ty: &Type) -> String {
    match ty {
        Type::Primitive {
            prim: PrimitiveType::Int | PrimitiveType::Int64 | PrimitiveType::UInt64,
        } => "int".to_string(),
        Type::Primitive {
            prim: PrimitiveType::Bool,
        } => "bool".to_string(),
        Type::Primitive {
            prim: PrimitiveType::Real,
        } => "real".to_string(),
        Type::Primitive {
            prim: PrimitiveType::String,
        } => "string".to_string(),
        Type::List { elem } => format!("seq<{}>", dafny_type(elem)),
        Type::Option { inner } => format!("seq<{}>", dafny_type(inner)),
        _ => "int".to_string(),
    }
}

fn lean_type(ty: &Type) -> String {
    match ty {
        Type::Primitive {
            prim: PrimitiveType::Int | PrimitiveType::Int64,
        } => "Int".to_string(),
        Type::Primitive {
            prim: PrimitiveType::UInt64,
        } => "Nat".to_string(),
        Type::Primitive {
            prim: PrimitiveType::Bool,
        } => "Bool".to_string(),
        Type::Primitive {
            prim: PrimitiveType::String,
        } => "String".to_string(),
        Type::List { elem } => format!("Array {}", lean_type(elem)),
        Type::Option { inner } => format!("Option {}", lean_type(inner)),
        _ => "Int".to_string(),
    }
}

