//! Track C academic publication targets: LaTeX (`algorithm2e`) and Typst (`lovelace`).

use crate::common::{CodeGenerator, GeneratedArtifact};
use ueas_hir::hir::Program;

pub struct LatexTarget;
pub struct TypstTarget;

impl CodeGenerator for LatexTarget {
    fn target_id(&self) -> &'static str {
        "latex"
    }
    fn file_extension(&self) -> &'static str {
        "tex"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from("% Generated by UEAS v2.0 LatexTarget (algorithm2e)\n");
        for algo in &program.algorithms {
            out.push_str("\\begin{algorithm}[H]\n\\DontPrintSemicolon\n");
            let params: Vec<String> = algo.parameters.iter().map(|p| p.name.clone()).collect();
            out.push_str(&format!(
                "\\Caption{{\\textsc{{{}}}({})}}\n",
                algo.name,
                params.join(", ")
            ));
            if let Some(t) = &algo.complexity.time {
                out.push_str(&format!("\\KwComplexity{{Time: ${}$}}\n", t.raw));
            }
            out.push_str("\\end{algorithm}\n\n");
        }
        Ok(GeneratedArtifact {
            target: "latex".to_string(),
            extension: "tex".to_string(),
            code: out,
            test_code: None,
        })
    }
}

impl CodeGenerator for TypstTarget {
    fn target_id(&self) -> &'static str {
        "typst"
    }
    fn file_extension(&self) -> &'static str {
        "typ"
    }
    fn generate(&self, program: &Program) -> Result<GeneratedArtifact, String> {
        let mut out = String::from("// Generated by UEAS v2.0 TypstTarget\n");
        for algo in &program.algorithms {
            let params: Vec<String> = algo.parameters.iter().map(|p| p.name.clone()).collect();
            out.push_str(&format!(
                "#figure(caption: [Algorithm {}({})])[```\n",
                algo.name,
                params.join(", ")
            ));
            if let Some(t) = &algo.complexity.time {
                out.push_str(&format!("Time: {}\n", t.raw));
            }
            out.push_str("```]\n\n");
        }
        Ok(GeneratedArtifact {
            target: "typst".to_string(),
            extension: "typ".to_string(),
            code: out,
            test_code: None,
        })
    }
}
